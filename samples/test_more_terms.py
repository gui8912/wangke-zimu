#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""扩充词表后的边界测试：长词优先、语气助词保护、标点要求"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import clean_transcript as CT

BASE = Path(__file__).resolve().parent.parent
C = CT.Cleaner(CT.load_rules(BASE / "rules" / "filler_words.json"),
               CT.load_corrections(BASE / "terms" / "corrections.txt"))

CASES = [
    # ── 长词优先：2 字词不能被 1 字词截断 ──
    ("嗯哼", "嗯哼，我知道。", "我知道。"),
    ("哎呀", "哎呀，这个事。", "这个事。"),
    ("哎哟", "哎哟，疼。", "疼。"),
    ("啊哈", "啊哈，原来如此。", "原来如此。"),
    ("哦哟", "哦哟，这么贵。", "这么贵。"),

    # ── 语气助词：句尾删，不伤实词和完整问句 ──
    ("你呢保留", "你呢？", "你呢？"),
    ("我呢保留", "我呢，觉得可以。", "我呢，觉得可以。"),
    ("东西呢删除", "东西呢？", "东西？"),
    ("今天下午呢", "今天下午呢，我们讲。", "今天下午，我们讲。"),
    ("干嘛不删", "你干嘛去了？", "你干嘛去了？"),
    ("好啦", "好啦，走吧。", "好，走。"),
    ("走呗", "走呗。", "走。"),
    ("好哇", "好哇，就这么办。", "好，就这么办。"),

    # ── punct_only：可能当实词的，只在句末/标点前删 ──
    ("你看那边保留", "你看那边。", "你看那边。"),
    ("你看逗号删", "你看，这个证照。", "这个证照。"),

    # ── 新增口头冗余 ──
    ("说实话", "说实话，这个不好办。", "这个不好办。"),
    ("说实话无逗号", "说实话这个不好办。", "这个不好办。"),
    ("你知道吗", "你知道吗，这很关键。", "这很关键。"),
    ("其实呢", "其实呢，这事不难。", "这事不难。"),
    ("但是呢留但是", "但是呢，我们要注意。", "但是，我们要注意。"),
    ("我跟你讲", "我跟你讲，这个批号有问题。", "这个批号有问题。"),

    # ── 句尾确认：只收删后主句仍完整的 ──
    ("好不好用不动", "这个好不好用？", "这个好不好用？"),
    ("对不对删", "这样做对不对？", "这样做。"),
    ("是吧删", "是这样吧？", "是这样？"),

    # ── 句首填充 ──
    ("那什么", "那什么，我们开始。", "我们开始。"),
    ("这个文件保留", "这个文件要备案。", "这个文件要备案。"),
]

ok = fail = 0
for label, src, want in CASES:
    got, ch, wn = C.clean(src)
    good = got == want
    ok += good
    fail += (not good)
    print(f"[{'OK  ' if good else 'FAIL'}] {label}")
    if not good:
        print(f"       输入：{src}")
        print(f"       期望：{want}")
        print(f"       实际：{got}")

print(f"\n通过 {ok} / {ok + fail}")
sys.exit(0 if fail == 0 else 1)
