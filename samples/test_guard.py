#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""五类填充词 + 七组判别的实测脚本"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import clean_transcript as CT

RULES = Path(__file__).resolve().parent.parent / "rules" / "filler_words.json"
CORR = Path(__file__).resolve().parent.parent / "terms" / "corrections.txt"

C = CT.Cleaner(CT.load_rules(RULES), CT.load_corrections(CORR))

SAMPLE = (
    "嗯，这个，各位同事啊，那么今天下午呢，我们主要是讲一下这个，就是药品零售企业，"
    "那个，日常检查的一些要点。那么首先呢，我先说一下啊，我们到了现场，第一个，"
    "就是要看它的这个证照是不是齐全，对吧？然后呢，这个执业药师是不是在岗，"
    "这个是很重要的一条，很重要的一个方面。然后的话，就是说，还要看它的这个药品陈列，"
    "那个，处方药和非处方药有没有分开，这个样子。嗯，基本上就是这些，发现问题呢，"
    "我们就要，这个，依法依规地进行处理，对吧？"
)


def run(label, text, expect_keep=(), expect_gone=()):
    out, changes, warns = C.clean(text)
    ok = True
    for k in expect_keep:
        if k not in out:
            ok = False
    for k in expect_gone:
        if k in out:
            ok = False
    flag = "OK  " if ok else "FAIL"
    print(f"[{flag}] {label}")
    print(f"       原：{text}")
    print(f"       后：{out}")
    if changes:
        print(f"       改动：{'；'.join(f'{a} {b}' for a, b, _ in changes)}")
    if C.last_suggestions:
        print(f"       建议：{'；'.join(C.last_suggestions)}")
    print()
    return ok


print("=" * 78)
print("一、用户样本全文")
print("=" * 78)
out, ch, wn = C.clean(SAMPLE)
print(out)
print()
print("字数：", len(SAMPLE), "→", len(out), f"（删 {100*(1-len(out)/len(SAMPLE)):.0f}%）")
print("改动：", "；".join(f"{a} {b}" for a, b, _ in ch))
print("建议：", "；".join(C.last_suggestions) or "无")

print()
print("=" * 78)
print("二、逐条判别")
print("=" * 78)

cases = [
    # 语气词：全部删
    ("语气词全部删", "嗯，啊，呃，哦，诶，哎，这个事要注意。",
     ("这个事要注意",), ("嗯", "啊", "呃", "哦", "诶", "哎")),
    # 结尾叹词只在句尾删，不伤实词
    ("嘛/哈 不伤实词", "你干嘛去了？哈哈，是这样嘛。",
     ("干嘛", "哈哈"), ()),
    # 句首填充：无指代删
    ("句首填充无指代", "这个，就是说，我们要注意。", ("要注意",), ("这个", "就是说")),
    # 有指代保留
    ("这个+名词保留", "这个文件，那个条款，这个批号都要看。",
     ("这个文件", "那个条款", "这个批号"), ()),
    # 句尾确认
    ("句尾确认删除", "证照是不是齐全，对吧？", ("齐全？",), ("对吧",)),
    ("是不是在岗不删", "要看执业药师是不是在岗。", ("是不是在岗",), ()),
    # 口头冗余
    ("口头冗余整体删", "那个啥，怎么说呢，我这么说吧，要查。", ("要查",),
     ("那个啥", "怎么说呢", "我这么说吧")),
    # 组合填充优先
    ("组合填充整体删", "这个就是说呢，然后的话，重点在这。", ("重点在这",),
     ("这个就是说", "然后的话")),
    # 所以说：有因果保留
    ("所以说有因果保留", "因为冷链断了，所以说这批药不能用了。",
     ("所以说",), ()),
    ("所以说无因果删除", "所以说，我们要注意。", ("我们要注意",), ("所以说",)),
    # 这样的话：条件句保留
    ("这样的话条件句保留", "这样的话就可以了。", ("这样的话",), ()),
    ("这样的话填充删除", "这样的话，我们先看证照。", ("先看证照",), ("这样的话",)),
    # 我们：单位自称只建议
    ("我们单位自称", "我们的监管要求是这样的。", ("我们的监管要求",), ()),
    ("我们泛称引导", "我们来看这个案例。", ("来看这个案例",), ("我们",)),
    # 其实：转折保留
    ("其实表转折保留", "其实是这样，并不是那样。", ("其实是这样",), ()),
    ("其实口头禅删除", "其实，这个问题要注意。", ("这个问题要注意",), ("其实",)),
    # 约量
    ("基本上无数据删", "基本上就是这些。", ("就是这些",), ("基本上",)),
    # 【修改 v1.4】断言改为只验「约量词不被当填充词删」。
    # 原来写死 ("大概三十",) / ("差不多五万",) 会与数字规整冲突（ITN 会转成 30 / 5万），
    # 而这两条用例的本意是保护约量词，与数字写法无关。
    ("大概含数字保留", "大概三十个工作日能办完。", ("大概",), ()),
    ("差不多含金额保留", "差不多五万元左右。", ("差不多",), ()),
    # 【新增 v1.4】「额」是语气词，但也是常用词的词内字，无条件 replace 会改坏专业表述
    ("金额不被误删", "货值金额五十万元。", ("金额",), ()),
    ("额度不被误删", "这个额度要控制。", ("额度",), ()),
    ("余额不被误删", "账户余额不足。", ("余额",), ()),
    ("限额不被误删", "超出限额了。", ("限额",), ()),
    ("句首额仍可删", "额，这个我们讲一下。", ("讲一下",), ()),
    # 解释
    ("换句话说有解释建议", "换句话说，这就是许可前置。", ("换句话说",), ()),
    ("可以说当填充删", "可以说非常重要。", ("非常重要",), ("可以说",)),
    # 引导
    ("请注意建议精简", "请注意，这里是重点。", ("请注意",), ()),
]

allok = True
for label, text, keep, gone in cases:
    allok &= run(label, text, keep, gone)

print("=" * 78)
print("全部通过" if allok else "有未通过用例")
print("=" * 78)
# 【修改 v1.4】原来无论成败都返回 0，自动化跑整套回归时无法发现失败
sys.exit(0 if allok else 1)
